  let current = "en";

  function pick(code) {
    if (S[code]) return code;
    const base = String(code || "").slice(0, 2);
    if (S[base]) return base;
    const variant = Object.keys(S).find((k) => k.startsWith(base + "-"));
    return variant || "en";
  }

  return {
    has: (code) => Boolean(S[pick(code)]),
    set(code) { current = pick(code); return current; },
    get: () => current,
    /* Fuer Texte, die an jemanden gehen, der unsere Sprache gerade nicht
       spricht - die Einladung vor allem. Wer eingeladen wird, versteht
       den Absender ja per Annahme nicht; Englisch ist der kleinste
       gemeinsame Nenner, den beide zumindest erkennen. */
    en(key, vars) {
      return this.inSprache("en", key, vars);
    },
    /* Ein Text in einer fest gewaehlten Sprache, egal was eingestellt ist. */
    inSprache(code, key, vars) {
      const q = S[pick(code)] || S.en;
      let s = q[key] || S.en[key] || key;
      if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
      return s;
    },
    /* t("joined", {name: "João"}) */
    t(key, vars) {
      let s = (S[current] && S[current][key]) || S.en[key] || key;
      if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
      return s;
    },
  };
